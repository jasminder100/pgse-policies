#!/usr/bin/env bash
# Regenerates gitops/*/kustomization.yaml from the repo layout.
# Argo CD syncs gitops/ in sync waves: platform(0) -> templates(1) -> constraints(2) -> waivers(3).
# Run after adding/removing a policy, namespace, RBAC file or waiver.
set -euo pipefail
cd "$(dirname "$0")/.."
shopt -s nullglob

gen() {  # gen <layer> <wave> <files...>
  local layer=$1 wave=$2; shift 2
  mkdir -p "gitops/$layer"
  {
    echo "# GENERATED by scripts/gen-gitops.sh - do not edit by hand"
    echo "apiVersion: kustomize.config.k8s.io/v1beta1"
    echo "kind: Kustomization"
    echo "commonAnnotations:"
    echo "  argocd.argoproj.io/sync-wave: \"$wave\""
    echo "resources:"
    for f in "$@"; do echo "  - ../../$f"; done
  } > "gitops/$layer/kustomization.yaml"
}

gen platform    0 crds/*.yaml gatekeeper/*.yaml namespaces/*.yaml rbac/*.yaml dashboards/*.yaml projects/*.yaml
gen templates   1 $(find policies -name template.yaml   | sort)
gen constraints 2 $(find policies -name constraint.yaml | sort)
gen waivers     3 waivers/*.yaml
gen apps        4 apps/*.yaml

cat > gitops/kustomization.yaml <<'KEOF'
# Entry point Argo CD syncs. Do not edit layer lists by hand; run scripts/gen-gitops.sh.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - platform
  - templates
  - constraints
  - waivers
  - apps
KEOF

echo "gitops/ regenerated"
